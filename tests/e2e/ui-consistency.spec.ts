import { expect, test, type Page } from '@playwright/test'
import { failApplicationRequest, login, navigate, openTopbarMenu, openMusicPlayer, resetListeningSession, uploadFixture } from './helpers'

const root = '00000000-0000-0000-0000-000000000000'
const origin = (process.env.E2E_BASE_URL || 'http://127.0.0.1:18080').replace(/\/$/, '')
const headers = { Origin: origin }

async function fitsViewport(page: Page, selector: string) {
  const bounds = (await page.locator(selector).boundingBox())!
  const viewport = page.viewportSize()!
  expect(bounds.x).toBeGreaterThanOrEqual(0)
  expect(bounds.y).toBeGreaterThanOrEqual(0)
  expect(bounds.x + bounds.width).toBeLessThanOrEqual(viewport.width + 1)
  expect(bounds.y + bounds.height).toBeLessThanOrEqual(viewport.height + 1)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(viewport.width)
}

for (const mobile of [false, true]) for (const colorScheme of ['light', 'dark'] as const) {
  test.describe(`${mobile ? 'mobile' : 'desktop'} ${colorScheme} UI`, () => {
    test.use({ viewport: mobile ? { width: 320, height: 640 } : { width: 1280, height: 900 }, isMobile: mobile, hasTouch: mobile, colorScheme, timezoneId: 'Asia/Shanghai' })

    test('history isolates scrolling, localizes dates and confirms restoration without losing current content', async ({ page }) => {
      const errors: string[] = []
      page.on('pageerror', error => errors.push(error.message))
      await login(page)
      const name = `ui-history-${Date.now()}-${mobile}-${colorScheme}.md`
      const created = await page.request.post('/api/documents', { headers, data: { parent_id: root, name, content: '原始版本\n' + '长行'.repeat(2000) + '\n' + '预览内容\n'.repeat(1200) } })
      expect(created.ok()).toBeTruthy()
      let file = await created.json()
      try {
        for (let index = 0; index < 20; index++) {
          const updated = await page.request.put(`/api/files/${file.id}/content`, { headers, data: { etag: file.etag, content: `已保存版本 ${index}` } })
          expect(updated.ok()).toBeTruthy()
          file = await updated.json()
        }
        await page.goto(`/f/${root}`)
        await page.getByLabel('打开搜索', { exact: true }).click()
        await page.getByLabel('搜索文件名').fill(name)
        await page.getByLabel('搜索文件名').press('Enter')
        await page.locator('.file-card').click()
        const editor = page.locator('.document-editor')
        const text = editor.getByLabel('文档内容')
        await expect(text).toHaveValue('已保存版本 19')
        await fitsViewport(page, '.document-editor')
        expect(await text.evaluate(element => element.clientHeight)).toBeGreaterThan(200)
        const trigger = editor.getByRole('button', { name: '版本历史', exact: true })
        await trigger.click()
        const history = editor.getByRole('complementary', { name: '版本历史', exact: true })
        await expect(history.locator('.history-row')).toHaveCount(20)
        await fitsViewport(page, '.version-history')
        await expect(page.locator('body')).toHaveCSS('overflow', 'hidden')
        await expect(page.locator('.ui-dialog-backdrop')).toHaveCount(1)
        await expect(editor.locator('.editor-body')).not.toHaveAttribute('inert', '')
        const stamp = history.locator('time').first()
        const value = await stamp.getAttribute('datetime')
        const expected = await page.evaluate(value => {
          const date = new Date(value!)
          return `${date.getMonth() + 1}月${date.getDate()}日 ${String(date.getHours()).padStart(2, '0')}:${String(date.getMinutes()).padStart(2, '0')}`
        }, value)
        await expect(stamp).toHaveText(expected)
        expect(await history.locator('.history-list').evaluate(element => element.scrollHeight > element.clientHeight)).toBe(true)
        expect(await history.evaluate(element => element.scrollHeight <= element.clientHeight)).toBe(true)
        const oldest = history.locator('.history-row').last()
        await oldest.getByRole('button', { name: '查看', exact: true }).click()
        await expect(editor.getByLabel('历史版本内容')).toHaveValue(/原始版本/)
        expect(await editor.getByLabel('历史版本内容').evaluate(element => element.scrollHeight > element.clientHeight)).toBe(true)
        expect(await editor.getByLabel('历史版本内容').evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
        await editor.getByRole('button', { name: '返回当前文档', exact: true }).click()
        if (mobile) await editor.getByRole('button', { name: '历史记录', exact: true }).click()
        await oldest.getByRole('button', { name: '恢复此版本', exact: true }).click()
        const confirm = page.getByRole('dialog', { name: '恢复历史版本？', exact: true })
        await expect(confirm).toContainText('当前内容会保存到版本历史')
        await fitsViewport(page, '.app-dialog')
        expect((await (await page.request.get(`/api/files/${file.id}/content`)).json()).content).toBe('已保存版本 19')
        await page.keyboard.press('Escape')
        await expect(confirm).toBeHidden()
        await expect(history).toBeVisible()
        await expect(oldest.getByRole('button', { name: '恢复此版本', exact: true })).toBeFocused()
        await page.keyboard.press('Escape')
        await expect(history).toBeHidden()
        await expect(text).toBeFocused()
        await expect(text).toHaveValue('已保存版本 19')
        await text.fill('仍未保存的修改')
        await trigger.click()
        await expect(history.locator('.history-actions button').filter({ hasText: '恢复此版本' }).first()).toBeDisabled()
        await expect(history).toContainText('请先保存当前修改')
        await page.keyboard.press('Escape')
        await editor.getByRole('button', { name: '保存', exact: true }).click()
        await expect(editor.getByRole('button', { name: '保存', exact: true })).toBeDisabled()
        await trigger.click()
        const selected = history.locator('.history-row').first()
        await selected.getByRole('button', { name: '恢复此版本', exact: true }).click()
        await confirm.getByRole('button', { name: '确认恢复', exact: true }).click()
        await expect(history).toBeHidden()
        await expect(text).toHaveValue('已保存版本 19')
        const versions = await (await page.request.get(`/api/files/${file.id}/versions`)).json()
        expect(versions[0].size).toBe(Buffer.byteLength('仍未保存的修改'))
        await text.fill('保存失败时仍保留输入')
        const failedSave = await failApplicationRequest(page, `/api/files/${file.id}/content`, '模拟文档保存失败')
        await editor.getByRole('button', { name: '保存', exact: true }).click()
        await expect(editor.locator('.editor-notice-error')).toHaveText('模拟文档保存失败')
        await expect(text).toHaveValue('保存失败时仍保留输入')
        await fitsViewport(page, '.document-editor')
        await failedSave.clear()
        expect(errors).toEqual([])
      } finally {
        await page.request.delete(`/api/files/${file.id}`, { headers })
        await page.request.delete(`/api/trash/${file.id}`, { headers })
      }
    })

    test('audio and reader controls keep their theme, fit the screen and retain independent paper/night preferences', async ({ page }) => {
      await login(page)
      await resetListeningSession(page)
      const suffix = `${Date.now()}-${mobile}-${colorScheme}`
      const created = await page.request.post('/api/directories', { headers, data: { parent_id: root, name: `ui-viewers-${suffix}` } })
      expect(created.ok()).toBeTruthy()
      const folder = await created.json()
      try {
        const samples = 20 * 8000
        const wav = Buffer.alloc(44 + samples * 2)
        wav.write('RIFF'); wav.writeUInt32LE(wav.length - 8, 4); wav.write('WAVEfmt ', 8)
        wav.writeUInt32LE(16, 16); wav.writeUInt16LE(1, 20); wav.writeUInt16LE(1, 22)
        wav.writeUInt32LE(8000, 24); wav.writeUInt32LE(16000, 28); wav.writeUInt16LE(2, 32)
        wav.writeUInt16LE(16, 34); wav.write('data', 36); wav.writeUInt32LE(wav.length - 44, 40)
        const song = await uploadFixture(page, folder.id, `ui-audio-${suffix}.wav`, 'audio/wav', wav)
        const bookResponse = await page.request.post('/api/documents', { headers, data: { parent_id: folder.id, name: `ui-reader-${suffix}.txt`, content: '第一章\n阅读器保留纸张与夜间主题。\n\n'.repeat(250) } })
        expect(bookResponse.ok()).toBeTruthy()
        const book = await bookResponse.json()
        await page.goto(`/f/${folder.id}`)
        await page.locator('.file-card').filter({ hasText: song.name }).click()
        await openMusicPlayer(page)
        await page.getByLabel('打开音频播放器', { exact: true }).click()
        const audio = page.getByRole('dialog', { name: '音频播放器', exact: true })
        await fitsViewport(page, '.music-player-dialog')
        await audio.getByLabel('播放速度', { exact: true }).selectOption('1.5')
        await expect(audio.getByLabel('播放速度', { exact: true })).toHaveValue('1.5')
        await expect(audio.locator('.audio-play')).toHaveCSS('background-color', colorScheme === 'dark' ? 'rgb(220, 229, 221)' : 'rgb(37, 59, 59)')
        await expect(audio.locator('.audio-play')).toHaveCSS('color', colorScheme === 'dark' ? 'rgb(27, 36, 30)' : 'rgb(248, 249, 246)')
        await audio.getByLabel('收起音频播放器', { exact: true }).click()
        await expect(audio).toBeHidden()
        await navigate(page, '书籍')
        await page.getByRole('button', { name: `打开 ${book.name}`, exact: true }).click()
        await expect(page.locator('#loading')).toBeHidden()
        await fitsViewport(page, '#reader-view')
        const reader = page.locator('#reader-view')
        // Reading preferences belong to the account, independently of the OS theme.
        if (await reader.evaluate(element => element.classList.contains('dark'))) await page.locator('#theme-button').click()
        await expect(reader).toHaveCSS('color-scheme', 'light')
        await page.locator('#font-button').click()
        await fitsViewport(page, '#font-popover')
        await page.locator('#font-larger').click()
        await page.locator('#font-button').click()
        await page.locator('#theme-button').click()
        await expect(reader).toHaveCSS('color-scheme', 'dark')
        await expect(reader).toHaveCSS('background-color', 'rgb(34, 37, 36)')
        await page.locator('#reader-back').click()
      } finally {
        await page.request.delete(`/api/files/${folder.id}`, { headers })
        await page.request.delete(`/api/trash/${folder.id}`, { headers })
      }
    })

    test('shared dialogs, controls and every page use the same theme and dismiss one layer at a time', async ({ page }) => {
      const errors: string[] = []
      page.on('pageerror', error => errors.push(error.message))
      await login(page)
      const surface = colorScheme === 'dark' ? 'rgb(36, 46, 39)' : 'rgb(255, 255, 255)'
      for (const name of ['首页', '书籍', '音乐', '图片', '视频', '文件', '回收站']) {
        await navigate(page, name)
        expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(page.viewportSize()!.width)
      }
      await page.getByLabel('打开账户设置', { exact: true }).click()
      await expect(page.locator('.account-modal')).toHaveCSS('background-color', surface)
      await page.locator('.password-entry').click()
      const subdialog = page.locator('.account-subdialog')
      await expect(subdialog).toHaveCSS('background-color', surface)
      await expect(subdialog.locator('input').first()).toHaveCSS('background-color', surface)
      await fitsViewport(page, '.account-subdialog')
      await page.keyboard.press('Escape')
      await expect(subdialog).toBeHidden()
      await expect(page.locator('.account-modal')).toBeVisible()
      await page.keyboard.press('Escape')
      await expect(page.locator('.account-modal')).toBeHidden()
      await navigate(page, '文件')
      await openTopbarMenu(page)
      await page.getByLabel('新建', { exact: true }).click()
      await page.getByRole('button', { name: '新建文件夹', exact: true }).click()
      const action = page.locator('.app-dialog')
      await expect(action).toHaveCSS('background-color', surface)
      await expect(action.locator('input')).toBeFocused()
      await fitsViewport(page, '.app-dialog')
      await page.keyboard.press('Escape')
      await expect(action).toBeHidden()
      const fault = await failApplicationRequest(page, '/api/library/items', '读取最近使用失败', { recent: 'true', opened_only: 'true' })
      await navigate(page, '首页')
      await expect(page.getByLabel('重试最近使用')).toBeVisible()
      await expect(page.getByLabel('重试最近使用')).toHaveCSS('border-radius', '10px')
      expect(await fault.hits()).toBeGreaterThan(0)
      await fault.clear()
      expect(errors).toEqual([])
    })
  })
}
